    words = "one two three four five six seven eight".split()
    expect(f"{words[n96 - 1]} of the eight battery" in TEX,
           f"battery >=0.96 count {n96} not worded in tex", errs)
    sat_max = max(t["var_init"] + t["e_pq_sampling"]
                  for t in v1t.values() if t["sr_observed"] >= 0.96)
    non_min = min(t["var_init"] + t["e_pq_sampling"]
                  for t in v1t.values() if t["sr_observed"] < 0.96)
    expect(sat_max < non_min,
           f"saturated total var {sat_max:.5f} no longer below non-saturated {non_min:.5f}", errs)
    expect(f"at most ${sat_max:.3f}$" in TEX,
           f"saturated max total variance {sat_max:.3f} not in tex", errs)

    import statistics
    mdes = sorted(c["mde_points"] for c in audit["comparisons"] if c["mde_points"] is not None)
    med_mde = statistics.median(mdes)
    expect(f"${med_mde:g}$" in TEX, f"median per-comparison MDE {med_mde:g} not in tex", errs)

    cc2 = fus["camera_confirmatory"]
    expect(f"${cc2['sr_s1']:.4f}$" in TEX, f"camconf s1 {cc2['sr_s1']:.4f} not in tex", errs)
    expect(f"${cc2['sr_s10']:.4f}$" in TEX, f"camconf s10 {cc2['sr_s10']:.4f} not in tex", errs)
